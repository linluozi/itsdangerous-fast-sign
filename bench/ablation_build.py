"""Build ablation trees: one optimisation disabled at a time.

The flags are read from ``itsdangerous/_ablation.py`` which the build writes;
every module consults them, so each variant is a real code path and not a
monkeypatch that could be optimised away.
"""

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

TEMPLATE = '''"""Ablation switches generated by bench/ablation_build.py.

Not part of the optimized build: only the ablation trees contain this file.
"""

ZLIB_GATE = {zlib_gate}
REUSE_SIGNER = {reuse_signer}
CACHE_KEYS = {cache_keys}
FAST_HMAC = {fast_hmac}
FAST_B64 = {fast_b64}
'''

#: (name, dict of flags that differ from the full optimisation)
VARIANTS = {
    "ablation_full": {},
    "ablation_no_zlib_gate": {"zlib_gate": False},
    "ablation_no_signer_reuse": {"reuse_signer": False, "cache_keys": False},
    "ablation_no_key_cache": {"cache_keys": False},
    "ablation_no_fast_hmac": {"fast_hmac": False},
    "ablation_no_fast_b64": {"fast_b64": False},
    "ablation_legacy_baseline": {
        "zlib_gate": False,
        "reuse_signer": False,
        "cache_keys": False,
        "fast_hmac": False,
        "fast_b64": False,
    },
}


def build(src_tree: str, out_root: str) -> list[str]:
    made = []

    for name, flags in VARIANTS.items():
        dst = os.path.join(out_root, name)

        if os.path.isdir(dst):
            shutil.rmtree(dst)

        shutil.copytree(
            os.path.join(src_tree, "src", "itsdangerous"),
            os.path.join(dst, "src", "itsdangerous"),
            ignore=shutil.ignore_patterns("__pycache__"),
        )

        values = {
            "zlib_gate": True,
            "reuse_signer": True,
            "cache_keys": True,
            "fast_hmac": True,
            "fast_b64": True,
        }
        values.update(flags)

        with open(
            os.path.join(dst, "src", "itsdangerous", "_ablation.py"),
            "w",
            encoding="utf-8",
            newline="\n",
        ) as f:
            f.write(TEMPLATE.format(**values))

        made.append(dst)

    return made


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "work")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "ablation")
    for path in build(src, out):
        print(path)
